function atlasEntries(entries, atlas, firstTile = 0) {
  return entries.map(([day, name, x, y, width, surface, angle = 0, heightScale = 1], index) => ({
    day, name, x, y, width, surface, angle, heightScale, atlas, tile:firstTile + index,
  }))
}

